export const nextThinkingIndex = (
  current: number,
  random: () => number = Math.random,
): number => {
  const count = THINKING_PHRASES.length;
  if (count <= 1) {
    return 0;
  }
  const offset = 1 + Math.floor(random() * (count - 1));
  return (current + offset) % count;
};
