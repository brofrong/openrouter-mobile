const titleCaseWord = (value: string): string => {
  const first = value[0];
  if (first === undefined) {
    return value;
  }
  return first.toUpperCase() + value.slice(1);
};

const wordsFromId = (value: string): string =>
  value
    .replaceAll("_", " ")
    .replaceAll("-", " ")
    .split(" ")
    .filter((part) => part.length > 0)
    .map(titleCaseWord)
    .join(" ");

export const speechVoiceLabel = (voice: string): string => {
  const azure = /^(?:[a-z]{2}-[A-Z]{2})-([^:]+):/.exec(voice);
  const azureName = azure?.[1];
  if (azureName !== undefined) {
    return azureName;
  }
  if (voice.startsWith("aura-2-")) {
    const rest = voice.slice("aura-2-".length);
    const [name] = rest.split("-");
    return name === undefined ? voice : titleCaseWord(name);
  }
  if (voice.startsWith("English_")) {
    return wordsFromId(voice.slice("English_".length));
  }
  const underscored = voice.split("_");
  if (underscored.length > 1) {
    const locale = underscored[0];
    const parts =
      locale !== undefined && locale.length <= 2
        ? underscored.slice(1)
        : underscored;
    return parts.map(titleCaseWord).join(" ");
  }
  return titleCaseWord(voice);
};
